param(
    [string]$IdlPath = "target/idl/chainbound_game.json",
    [string]$CanonicalIdlPath = "idl/chainbound_game.json",
    [string]$OutputPath = "../../Assets/Scripts/Solana/Programs/Generated/ChainboundGameProgramContract.Generated.cs"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$idlFile = [IO.Path]::GetFullPath((Join-Path $root $IdlPath))
$outputFile = [IO.Path]::GetFullPath((Join-Path $root $OutputPath))
$canonicalIdlFile = [IO.Path]::GetFullPath((Join-Path $root $CanonicalIdlPath))
$idl = Get-Content -Raw -LiteralPath $idlFile | ConvertFrom-Json

function Pascal([string]$value) {
    return (($value -split '_') | ForEach-Object {
        if ($_.Length -eq 0) { return "" }
        $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1)
    }) -join ''
}

function Bytes($values) { return ($values | ForEach-Object { [string]$_ }) -join ', ' }
function Strings($values) { return ($values | ForEach-Object { '"' + $_ + '"' }) -join ', ' }
function Bools($values) { return ($values | ForEach-Object { if ($_ -eq $true) { 'true' } else { 'false' } }) -join ', ' }

$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// <auto-generated>')
$lines.Add('// Generated from backend/chainbound_game/target/idl/chainbound_game.json.')
$lines.Add('// Run backend/chainbound_game/scripts/generate-unity-client.ps1; do not edit by hand.')
$lines.Add('// </auto-generated>')
$lines.Add('using System;')
$lines.Add('using System.Collections.Generic;')
$lines.Add('using Chainbound.Solana;')
$lines.Add('namespace Chainbound.Combat')
$lines.Add('{')
$lines.Add('    public static class ChainboundGameProgramContract')
$lines.Add('    {')
$lines.Add(('        public const string ProgramId = "{0}";' -f $idl.address))
$lines.Add('        public const string GameConfigSeed = "game_config";')
$lines.Add('')

foreach ($ix in $idl.instructions) {
    $name = Pascal $ix.name
    $lines.Add(('        public const string {0} = "{1}";' -f $name, $ix.name))
    $lines.Add(('        public static readonly byte[] {0}Discriminator = {{ {1} }};' -f $name, (Bytes $ix.discriminator)))
    $lines.Add(('        public static readonly string[] {0}Accounts = {{ {1} }};' -f $name, (Strings ($ix.accounts | ForEach-Object name))))
    $lines.Add(('        public static readonly bool[] {0}Writable = {{ {1} }};' -f $name, (Bools ($ix.accounts | ForEach-Object writable))))
    $lines.Add(('        public static readonly bool[] {0}Signer = {{ {1} }};' -f $name, (Bools ($ix.accounts | ForEach-Object signer))))
    $lines.Add('')
}

foreach ($account in $idl.accounts) {
    $name = Pascal $account.name
    $lines.Add(('        public static readonly byte[] {0}AccountDiscriminator = {{ {1} }};' -f $name, (Bytes $account.discriminator)))
}

$lines.Add('')
$lines.Add('        public static List<AccountMeta> BuildAccounts(string[] names, bool[] writable, bool[] signer, IReadOnlyDictionary<string, PublicKey> addresses)')
$lines.Add('        {')
$lines.Add('            if (names == null || writable == null || signer == null || names.Length != writable.Length || names.Length != signer.Length)')
$lines.Add('                throw new ArgumentException("Generated account metadata arrays are inconsistent.");')
$lines.Add('            var result = new List<AccountMeta>(names.Length);')
$lines.Add('            for (int i = 0; i < names.Length; i++)')
$lines.Add('            {')
$lines.Add('                if (!addresses.TryGetValue(names[i], out PublicKey key))')
$lines.Add('                    throw new ArgumentException($"Missing generated instruction account: {names[i]}.", nameof(addresses));')
$lines.Add('                result.Add(writable[i] ? AccountMeta.Writable(key, signer[i]) : AccountMeta.ReadOnly(key, signer[i]));')
$lines.Add('            }')
$lines.Add('            return result;')
$lines.Add('        }')

$lines.Add('    }')
$lines.Add('}')
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($outputFile)) | Out-Null
[IO.File]::WriteAllLines($outputFile, $lines, [Text.UTF8Encoding]::new($false))
[IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($canonicalIdlFile)) | Out-Null
[IO.File]::WriteAllText($canonicalIdlFile, (Get-Content -Raw -LiteralPath $idlFile), [Text.UTF8Encoding]::new($false))
Write-Output $outputFile
Write-Output $canonicalIdlFile
