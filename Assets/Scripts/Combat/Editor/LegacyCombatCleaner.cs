        /// <summary>Open a scene, strip missing scripts from all GameObjects, save.</summary>
        private static int CleanScene(string scenePath)
        {
            // Save current scene first
            EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo();

            var scene = EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Single);
            int totalRemoved = 0;

            GameObject[] roots = scene.GetRootGameObjects();
            foreach (var root in roots)
            {
                totalRemoved += CleanGameObjectRecursive(root);
            }

            if (totalRemoved > 0)
            {
                EditorSceneManager.MarkSceneDirty(scene);
                EditorSceneManager.SaveScene(scene);
            }

            return totalRemoved;
        }

        /// <summary>Open a prefab, strip missing scripts, save.</summary>
        private static int CleanPrefab(string prefabPath)
        {
            // Open prefab in edit mode
            GameObject prefabRoot = PrefabUtility.LoadPrefabContents(prefabPath);
            if (prefabRoot == null) return 0;

            int totalRemoved = CleanGameObjectRecursive(prefabRoot);

            if (totalRemoved > 0)
            {
                PrefabUtility.SaveAsPrefabAsset(prefabRoot, prefabPath);
            }

            PrefabUtility.UnloadPrefabContents(prefabRoot);
            return totalRemoved;
        }

        /// <summary>
        /// Recursively strip missing MonoBehaviours from a GameObject and its children.
        /// Returns the number of components removed.
        /// </summary>
        private static int CleanGameObjectRecursive(GameObject go)
        {
            int removed = GameObjectUtility.RemoveMonoBehavioursWithMissingScript(go);

            for (int i = 0; i < go.transform.childCount; i++)
            {
                removed += CleanGameObjectRecursive(go.transform.GetChild(i).gameObject);
            }

            return removed;
        }
