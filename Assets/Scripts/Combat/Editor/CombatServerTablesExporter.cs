using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Chainbound.Combat.Editor
{
    /// <summary>Generates Supabase move tables from the same imported assets used by combat.</summary>
    public static class CombatServerTablesExporter
    {
        private const string ManifestRelativePath = "backend/Chainbound.BattleService/manifests/gameplay-manifest.json";
        private const string SharedRelativePath = "Supabase/functions/_shared";

        [MenuItem("Tools/Chainbound/Combat/Export Server Move Tables", priority = 341)]
        public static void ExportAll()
        {
            string projectRoot = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
            string outputRoot = Path.Combine(projectRoot, SharedRelativePath);
            Directory.CreateDirectory(outputRoot);
            IReadOnlyDictionary<string, string> outputs = BuildCurrentTables();
            foreach (KeyValuePair<string, string> output in outputs)
                File.WriteAllText(Path.Combine(outputRoot, output.Key), output.Value, new UTF8Encoding(false));
            AssetDatabase.Refresh();
            Debug.Log($"[CombatServerTablesExporter] Exported {LoadMoves().Count} move AP entries and server availability tables.");
        }

        public static IReadOnlyDictionary<string, string> BuildCurrentTables()
        {
            string projectRoot = Path.GetFullPath(Path.Combine(Application.dataPath, ".."));
            List<MoveDefinitionSO> moves = LoadMoves();
            Dictionary<string, MoveDefinitionSO> byId = moves.ToDictionary(x => x.moveId.Trim(), StringComparer.Ordinal);
            string manifestHash = HashFile(Path.Combine(projectRoot, ManifestRelativePath));
            string header = $"// GENERATED by CombatServerTablesExporter. Do not hand-edit. manifestHash={manifestHash}\n";
            return new Dictionary<string, string>(StringComparer.Ordinal)
            {
                ["move_ap.ts"] = BuildMoveAp(header, moves),
                ["move_flags.generated.ts"] = BuildMoveFlags(header, moves),
                ["known_pool.generated.ts"] = BuildKnownPools(header, byId),
            };
        }

        private static List<MoveDefinitionSO> LoadMoves()
        {
            var moves = new List<MoveDefinitionSO>();
            string[] guids = AssetDatabase.FindAssets("t:MoveDefinitionSO", new[] { "Assets/Data/Combat/Moves" });
            for (int i = 0; i < guids.Length; i++)
            {
                MoveDefinitionSO move = AssetDatabase.LoadAssetAtPath<MoveDefinitionSO>(AssetDatabase.GUIDToAssetPath(guids[i]));
                if (move != null && !string.IsNullOrWhiteSpace(move.moveId))
                    moves.Add(move);
            }
            return moves.OrderBy(x => x.moveId, StringComparer.Ordinal).ToList();
        }

        private static string BuildMoveAp(string header, List<MoveDefinitionSO> moves)
        {
            var sb = new StringBuilder(header);
            sb.AppendLine("/** Structural affordability only; runtime modifiers still determine effective cost. */");
            sb.AppendLine("export const PVP_AP_CAP = 10;");
            sb.AppendLine();
            sb.AppendLine("export const MOVE_AP_COST: Readonly<Record<string, number>> = {");
            for (int i = 0; i < moves.Count; i++)
                sb.AppendLine($"  \"{Escape(moves[i].moveId)}\": {Mathf.Max(0, moves[i].apCost)},");
            sb.AppendLine("};");
            sb.AppendLine();
            sb.AppendLine("export const MOVE_SPENDS_REMAINING_AP: ReadonlySet<string> = new Set([");
            foreach (MoveDefinitionSO move in moves.Where(x => HasTag(x, "SpendRemainingAp")))
                sb.AppendLine($"  \"{Escape(move.moveId)}\",");
            sb.AppendLine("]);");
            sb.AppendLine();
            sb.AppendLine("export function apCostForMove(moveId: string): number | null {");
            sb.AppendLine("  if (!moveId || !Object.prototype.hasOwnProperty.call(MOVE_AP_COST, moveId)) return null;");
            sb.AppendLine("  return MOVE_AP_COST[moveId];");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string BuildMoveFlags(string header, List<MoveDefinitionSO> moves)
        {
            var sb = new StringBuilder(header);
            sb.AppendLine("export const BOSS_ONLY_MOVE_IDS: ReadonlySet<string> = new Set([");
            foreach (MoveDefinitionSO move in moves.Where(MoveAvailability.IsBossOnly))
                sb.AppendLine($"  \"{Escape(move.moveId)}\",");
            sb.AppendLine("]);");
            sb.AppendLine();
            sb.AppendLine("export function isBossOnlyMove(moveId: string): boolean {");
            sb.AppendLine("  return BOSS_ONLY_MOVE_IDS.has((moveId ?? \"\").trim());");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string BuildKnownPools(string header, Dictionary<string, MoveDefinitionSO> moves)
        {
            VendingConfigSO vending = LoadFirst<VendingConfigSO>();
            IReadOnlyList<string> authored = vending != null ? vending.knownPoolMoveIds : Array.Empty<string>();
            var known = ResolveEntries(authored, moves, "Known pool", rejectNoCandy: true);
            var eventIds = new HashSet<string>(StringComparer.Ordinal);
            foreach (ManualEncounterProviderSO provider in LoadAll<ManualEncounterProviderSO>())
            {
                EncounterSnapshot encounter = provider.GenerateEncounter(0x514A4D);
                if (encounter?.victoryKnownGrants == null)
                    continue;
                for (int i = 0; i < encounter.victoryKnownGrants.Count; i++)
                {
                    string id = encounter.victoryKnownGrants[i].moveId?.Trim();
                    if (!string.IsNullOrEmpty(id))
                        eventIds.Add(id);
                }
            }
            var eventEntries = ResolveEntries(
                eventIds.OrderBy(x => x, StringComparer.Ordinal).ToList(),
                moves,
                "Event Known grant",
                rejectNoCandy: false);

            var sb = new StringBuilder(header);
            sb.AppendLine("export interface GeneratedKnownMove { readonly moveId: string; readonly element: number; readonly basePower: number; }");
            sb.AppendLine();
            sb.AppendLine("export const KNOWN_POOL: readonly GeneratedKnownMove[] = [");
            AppendEntries(sb, known);
            sb.AppendLine("] as const;");
            sb.AppendLine();
            sb.AppendLine("export const EVENT_KNOWN_GRANT_CATALOG: Readonly<Record<string, { element: number; basePower: number }>> = {");
            for (int i = 0; i < eventEntries.Count; i++)
            {
                MoveDefinitionSO move = eventEntries[i];
                sb.AppendLine($"  \"{Escape(move.moveId)}\": {{ element: {(int)move.baseType}, basePower: {move.power} }},");
            }
            sb.AppendLine("};");
            return sb.ToString();
        }

        private static List<MoveDefinitionSO> ResolveEntries(
            IReadOnlyList<string> ids,
            Dictionary<string, MoveDefinitionSO> moves,
            string source,
            bool rejectNoCandy)
        {
            var result = new List<MoveDefinitionSO>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < ids.Count; i++)
            {
                string id = ids[i]?.Trim();
                if (string.IsNullOrEmpty(id) || !seen.Add(id))
                    continue;
                if (!moves.TryGetValue(id, out MoveDefinitionSO move))
                    throw new InvalidOperationException($"{source} references unknown move '{id}'.");
                if (!MoveAvailability.IsPlayerObtainable(move) || (rejectNoCandy && HasTag(move, "NO_CANDY")))
                    throw new InvalidOperationException($"{source} references unavailable move '{id}'.");
                result.Add(move);
            }
            return result;
        }

        private static void AppendEntries(StringBuilder sb, List<MoveDefinitionSO> entries)
        {
            for (int i = 0; i < entries.Count; i++)
            {
                MoveDefinitionSO move = entries[i];
                sb.AppendLine($"  {{ moveId: \"{Escape(move.moveId)}\", element: {(int)move.baseType}, basePower: {move.power} }},");
            }
        }

        private static T LoadFirst<T>() where T : UnityEngine.Object => LoadAll<T>().FirstOrDefault();

        private static List<T> LoadAll<T>() where T : UnityEngine.Object
        {
            var result = new List<T>();
            string[] guids = AssetDatabase.FindAssets($"t:{typeof(T).Name}");
            for (int i = 0; i < guids.Length; i++)
            {
                T value = AssetDatabase.LoadAssetAtPath<T>(AssetDatabase.GUIDToAssetPath(guids[i]));
                if (value != null)
                    result.Add(value);
            }
            return result;
        }

        private static bool HasTag(MoveDefinitionSO move, string expected)
        {
            if (move?.tags == null)
                return false;
            for (int i = 0; i < move.tags.Count; i++)
                if (string.Equals(move.tags[i], expected, StringComparison.OrdinalIgnoreCase))
                    return true;
            return false;
        }

        private static string HashFile(string path)
        {
            if (!File.Exists(path))
                return "unexported";
            using SHA256 sha = SHA256.Create();
            return BitConverter.ToString(sha.ComputeHash(File.ReadAllBytes(path))).Replace("-", "").ToLowerInvariant();
        }

        private static string Escape(string value) => (value ?? string.Empty).Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
}
